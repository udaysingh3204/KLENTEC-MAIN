import { Helmet } from "react-helmet-async";

interface SEOProps {
  title: string;
  description: string;
  path: string;
  image?: string;
}

const SITE_URL = "https://klentec.com";
const DEFAULT_IMAGE = `${SITE_URL}/social-preview.png`;

export const SEO = ({ title, description, path, image = DEFAULT_IMAGE }: SEOProps) => {
  const url = `${SITE_URL}${path}`;
  const fullTitle = title.includes("KLENTEC") ? title : `${title} | KLENTEC`;

  return (
    <Helmet>
      <title>{fullTitle}</title>
      <meta name="description" content={description} />
      <link rel="canonical" href={url} />
      <meta property="og:type" content="website" />
      <meta property="og:site_name" content="KLENTEC" />
      <meta property="og:title" content={fullTitle} />
      <meta property="og:description" content={description} />
      <meta property="og:url" content={url} />
      <meta property="og:image" content={image} />
      <meta name="twitter:card" content="summary_large_image" />
      <meta name="twitter:site" content="@klentec" />
      <meta name="twitter:title" content={fullTitle} />
      <meta name="twitter:description" content={description} />
      <meta name="twitter:image" content={image} />
    </Helmet>
  );
};
